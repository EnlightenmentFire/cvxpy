D = "零一二三四五六七八九"
def _int_cn(n):
    n = int(n)
    if n == 0: return "零"
    out = ""
    units = ["", "十", "百", "千"]
    s = str(n)
    if n >= 10000:
        hi, lo = divmod(n, 10000)
        r = _int_cn(hi) + "万"
        if lo: r += ("零" if lo < 1000 else "") + _int_cn(lo)
        return r
    L = len(s); zero = False
    for i, ch in enumerate(s):
        d = int(ch); u = L - 1 - i
        if d == 0: zero = True; continue
        if zero and out: out += "零"
        zero = False
        if d == 2 and u >= 2: out += "两"
        elif d == 1 and u == 1 and not out: out += ""
        else: out += D[d]
        out += units[u]
    return out
def num2cn(t):
    t = re.sub(r"(\d{4})年", lambda m: "".join(D[int(c)] for c in m.group(1)) + "年", t)
    t = re.sub(r"(\d+)\.(\d+)%", lambda m: "百分之" + _int_cn(m.group(1)) + "点" + "".join(D[int(c)] for c in m.group(2)), t)
    t = re.sub(r"(\d+)%", lambda m: "百分之" + _int_cn(m.group(1)), t)
    def q(m):
        n, nxt = m.group(1), m.group(2)
        r = _int_cn(n)
        if n == "2" and nxt in "万亿个次条倍吨": r = "两"
        return r + nxt
    t = re.sub(r"(\d+)(.?)", q, t)
    return t
def clean_tts(t):
    t = num2cn(t)
    for a in "「」《》": t = t.replace(a, "")
    return t

def lines():
    out = []
    for sid, sname, ls in SECTIONS:
        for (lid, sub, pause, src) in ls:
            out.append(dict(id=lid, sec=sid, secname=sname, sub=sub, tts=TTS_OVERRIDE.get(lid) or clean_tts(sub), pause=pause, src=src))
    return out

if __name__ == "__main__":
    L = lines()
    n = sum(len(re.sub(r"[，。：；？！、「」《》\s％%]", "", l["tts"])) for l in L)
    if len(sys.argv) > 1 and sys.argv[1] == "json":
        json.dump(dict(sections=[(s, n_) for s, n_, _ in SECTIONS], lines=L), open("script/script.json", "w"), ensure_ascii=False, indent=1)
    for l in L: print(l["id"], l["tts"])
    print("字数(读音)", n, "停顿合计", sum(l["pause"] for l in L))
