CLOCK = {"s02": "3月", "s03": "3月", "s04": "4/6", "s05": "4/9", "s06": "4/9", "s07": "4/9", "s08": "4/9",
         "s09": "5-10月", "s10": "11月", "s12": "1586"}
for _s in SCENES:
    _s["clock"] = CLOCK.get(_s["id"])

TTS_SUBS = [("森长可", "森常可"), ("砦", "寨"), ("《", ""), ("》", "")]


def all_lines():
    out = []
    for s in SCENES:
        for i, ln in enumerate(s["lines"]):
            cue, say = ln[0], ln[1]
            tts = ln[2] if len(ln) > 2 else say
            for a, b in TTS_SUBS:
                tts = tts.replace(a, b)
            out.append(dict(id=f"{s['id']}_{i:02d}", scene=s["id"], cue=cue, say=say, tts=tts))
    return out


