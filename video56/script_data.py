def all_lines():
    out = []
    for s in SCENES:
        for i, d in enumerate(s["lines"]):
            dd = dict(d)
            dd["id"] = f"{s['id']}_{i:02d}"
            dd["scene"] = s["id"]
            dd.setdefault("sub", dd["say"])
            dd.setdefault("gap", 0.5)
            out.append(dd)
    return out


