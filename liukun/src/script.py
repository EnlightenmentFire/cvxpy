# TTS 同音替换（只改读音易错的字；字幕仍用原字）
TTS_SUB = [
    ("并州", "冰州"), ("并土", "冰土"), ("刘琨", "刘昆"), ("琨", "昆"), ("祖逖", "祖替"),
    ("段匹磾", "段匹低"), ("匹磾", "匹低"), ("段末柸", "段末杯"), ("猗卢", "依卢"),
    ("箕澹", "基旦"), ("温峤", "温较"), ("卢谌", "卢臣"), ("令狐盛", "灵狐盛"),
    ("愍", "敏"), ("孑然", "节然"), ("稽聪", "机聪"), ("佻巧", "挑巧"), ("著鞭", "卓鞭"),
    ("负楯", "负盾"), ("属鞬而耨", "主坚而耨"), ("皆没", "皆末"), ("蓟城", "季城"),
    ("晋祚", "晋作"), ("河朔", "河硕"), ("欤", "于"), ("胡笳", "胡加"),
    ("“", ""), ("”", ""), ("《", ""), ("》", ""),
]
def tts_text(l):
    t = l.get("tts") or l["text"]
    for a, b in TTS_SUB:
        t = t.replace(a, b)
    return t

