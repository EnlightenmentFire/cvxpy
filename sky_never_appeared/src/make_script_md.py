def main():
    meta = {}
    mp = os.path.join(os.environ.get('SKY_TTS_META', ''), 'meta.json')
    if os.path.exists(mp):
        meta = {m['id']: m['dur'] for m in json.load(open(mp))}
    out = ['# 冷战核按钮 · 第二期《一片没有出现的天空》解说稿 v1', '']
    total_chars = 0
    total_s = 0.0
    for sec, chapter, lines in S.SECTIONS:
        title, vis = VIS[sec]
        out.append(f'## {title}')
        out.append('')
        out.append(f'**画面**：{vis}')
        out.append('')
        for lid, text, pause, tags in lines:
            total_chars += len(re.sub(r'[，。；：？！、“”‘’《》（）—\-·\s0-9A-Za-z]', '', text))
            d = meta.get(lid)
            if d:
                total_s += d + pause
            tag = f'  `[{tags}]`' if tags else ''
            out.append(f'- {text}{tag}')
            if 'EN1' in tags or 'EN2' in tags:
                k = 'EN1' if 'EN1' in tags else 'EN2'
                c = S.EN_CLIPS[k]
                out.append(f'    - 〔原声〕*{c["en"]}*')
                out.append(f'    - 〔字幕〕{"，".join(c["zh"])}')
        out.append('')
    head = [f'- 旁白约 {total_chars} 字' + (f'；按当前样音语速，旁白（含停顿）约 {total_s / 60:.1f} 分钟，加上无旁白的画面段和原声，成片约 {total_s / 60 + 1.0:.0f} 分钟' if total_s else ''),
            '- 带 `[...]` 的是画面提示点；「假想」段落见每段"画面"说明',
            '- 史料核对和对提纲的更正，见 `notes_sources.md`', '']
    out[2:2] = head
    path = os.path.join(ROOT, 'script', 'script.md')
    open(path, 'w').write('\n'.join(out))
    print(path, total_chars, round(total_s / 60, 2))


if __name__ == '__main__':
    main()
