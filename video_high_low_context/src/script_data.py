"""《美国人到底怎么说话》结构化脚本。

每个 segment = 一章；items 按顺序播放：
  N(text)              旁白一句（中文，Qwen 克隆声音）
  Q(text, who)         中文引语（旁白声音，语速稍慢）
  E(...)               英文说法：英文配音 + 双层字幕（字面 / 真实意思 / 白话为什么）
  C(...)               中文说法：双层字幕（不另配英文）
  J(text)              日文读音
  BEAT(sec, tag)       画面停顿 / 音效节点
scene 字段告诉渲染器画什么背景插画。
"""


def N(text, **kw):
    return dict(kind="N", text=text, **kw)


def Q(text, who="", **kw):
    return dict(kind="Q", text=text, who=who, **kw)


def E(en, spk, lit, real, why="", say_lit="", say_real="", **kw):
    return dict(kind="E", en=en, spk=spk, lit=lit, real=real, why=why,
                say_lit=say_lit, say_real=say_real, **kw)


def C(zh, lit, real, why="", say="", **kw):
    return dict(kind="C", zh=zh, lit=lit, real=real, why=why, say=say, **kw)


def J(text, display, **kw):
    return dict(kind="J", text=text, display=display, **kw)


def BEAT(sec, tag="", **kw):
    return dict(kind="BEAT", sec=sec, tag=tag, **kw)


