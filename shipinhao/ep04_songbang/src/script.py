import re


def display(text):
    return re.sub(r"\{([^|}]*)\|([^}]*)\}", r"\1", text)


def spoken(text):
    t = re.sub(r"\{([^|}]*)\|([^}]*)\}", r"\2", text)
    t = t.replace("「", "").replace("」", "").replace("《", "").replace("》", "")
    return t


