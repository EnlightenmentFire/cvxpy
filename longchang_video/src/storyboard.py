ORDER = list(BOARD.keys())

LEAD_IN = 2.2          # 片头黑场到第一句
TITLE_AFTER = 'a04'    # 这句之后插入片名
TITLE_DUR = 5.8
END_CARD = 10.0        # 片尾：片名 + 出处


def hanzi(s):
    return re.sub(r'[^一-鿿]', '', s)


def default_gap(b):
    if b['gap'] is not None:
        return b['gap']
    glen = sum(len(hanzi(t)) for k, t in b['segs'] if k == 'G')
    if glen:
        return 1.05 + 0.03 * glen
    return 0.55


def build_timeline(durs):
    """durs: {beat_id: 配音时长}。返回 dict(beats={id: (t0, t1, t_next)}, title=(t0,t1), end=(t0,t1), total=)。"""
    t = LEAD_IN
    beats = {}
    title = None
    for bid in ORDER:
        d = durs[bid]
        t0, t1 = t, t + d
        t = t1 + default_gap(BOARD[bid])
        beats[bid] = [t0, t1, t]
        if bid == TITLE_AFTER:
            title = (t, t + TITLE_DUR)
            t += TITLE_DUR
            beats[bid][2] = title[0]
    end = (t, t + END_CARD)
    return dict(beats=beats, title=title, end=end, total=end[1])


def seg_times(bid, t0, t1):
    """一拍里每段出现的时刻：按已读字数的比例摊在配音时长上。G 跟着前一句 Q。"""
    segs = BOARD[bid]['segs']
    spoken = [len(hanzi(t)) if k in 'NQ' else 0 for k, t in segs]
    total = max(sum(spoken), 1)
    out, acc, last = [], 0, t0
    for (k, txt), n in zip(segs, spoken):
        if k == 'G':
            out.append(last + 0.30)
        else:
            last = t0 + (t1 - t0) * acc / total - (0.12 if acc else 0.10)
            out.append(last)
            acc += n
    return out


