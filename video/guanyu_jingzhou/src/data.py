def seg(path, lon0, lon1):
    """取河道上经度区间内的一段（按原顺序）。"""
    lo, hi = min(lon0, lon1), max(lon0, lon1)
    pts = [p for p in path if lo <= p[0] <= hi]
    return pts if lon0 <= lon1 else pts[::-1]

