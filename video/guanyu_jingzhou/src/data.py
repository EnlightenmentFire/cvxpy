_rv = load_rivers()
def _chain(parts):
    out = []
    for name, i0, rev in parts:
        segs = [l for n, r, l in _rv if n == name and abs(l[0][0] - i0) < 0.02]
        l = list(segs[0]); l = l[::-1] if rev else l
        out += l if not out else l[1:]
    return out
