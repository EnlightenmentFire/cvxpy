def all_lines():
    out = []
    for s in SCENES:
        for i, l in enumerate(s["lines"]):
            d = dict(l)
            d["id"] = f"{s['id']}{i + 1:02d}"
            d["scene"] = s["id"]
            d["vis"] = s["vis"]
            d.setdefault("tts", d["say"])
            out.append(d)
    return out


