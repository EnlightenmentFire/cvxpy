function drawRivers(cam, a = 1) {
  const w = clamp(cam.s * 9, 2.5, 9);
  const riv = (p, ww, al = 0.9) => geoLine(cam, p, { color: '#7fa9b4', w: ww, alpha: al * a });
  riv(G.jiang, w * 1.05, 0.75); riv(G.huai, w * 0.7, 0.7); riv(G.si, w * 0.6, 0.7); riv(G.han, w * 0.45, 0.6);
  riv(G.wei, w * 0.7, 0.8); riv(G.heUp, w * 0.95, 0.85);
  geoLine(cam, G.he, { color: '#c9b47a', w: w * 1.25, alpha: 0.95 * a, glow: 'rgba(220,190,120,0.5)', blur: 10 });
}
function riverNames(cam, a = 1, which = 'he') {
  const t = (s, lon, lat, sz = 30, col = '#d8caa0') => { const [x, y] = mw(cam, lon, lat); text(s, x, y, { size: sz, fam: SERIF, wt: 700, color: col, alpha: a * 0.95, align: 'center', ls: 8 }); };
  if (which.includes('he')) t('黄 河', 114.0, 35.62, 30);
  if (which.includes('wei')) t('渭水', 109.6, 34.72, 26, '#a9c9d2');
  if (which.includes('si')) t('泗水', 116.35, 35.1, 26, '#a9c9d2');
  if (which.includes('huai')) t('淮水', 117.3, 32.6, 26, '#a9c9d2');
  if (which.includes('jiang')) t('长 江', 117.3, 30.6, 28, '#a9c9d2');
}
