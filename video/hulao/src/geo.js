function tint(cam, poly, color, a) {
  if (a <= 0) return; ctx.save(); ctx.globalAlpha = a; ctx.fillStyle = color; ctx.filter = 'blur(28px)';
  ctx.beginPath(); poly.forEach((p, i) => { const [x, y] = mw(cam, p[0], p[1]); i ? ctx.lineTo(x, y) : ctx.moveTo(x, y); }); ctx.closePath(); ctx.fill(); ctx.restore();
}
