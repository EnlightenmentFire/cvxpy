function drawRivers(cam, a = 1) {
  const r = cam.k / PL.macro.scale, w = clamp(r * 9, 2.5, 9), wh = clamp(r * 9, 2.5, 70);
  const riv = (p, ww, al = 0.9) => geoLine(cam, p, { color: '#6f97a3', w: ww, alpha: al * a });
  if (cam.wdeg > 3) { riv(G.jiang, w * 1.05, 0.7); riv(G.huai, w * 0.7, 0.65); riv(G.si, w * 0.6, 0.65); riv(G.han, w * 0.45, 0.55); riv(G.heUp, w * 0.95, 0.8); }
  riv(G.wei, w * 0.7, 0.78); riv(G.luo, clamp(r * 3, 1.5, 14), 0.6);
  geoLine(cam, G.he, { color: wh > 20 ? '#a8956a' : '#bfa970', w: wh * 1.25, alpha: (wh > 20 ? 0.82 : 0.95) * a, glow: 'rgba(210,180,110,0.45)', blur: 10 });
}
