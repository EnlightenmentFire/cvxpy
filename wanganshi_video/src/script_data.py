def all_lines():
    out = []
    for s in SCENES:
        for i, d in enumerate(s["lines"]):
            dd = dict(d)
            dd["id"] = f"{s['id']}_{i + 1:02d}"
            dd["scene"] = s["id"]
            dd["vis"] = s["vis"]
            out.append(dd)
    return out


