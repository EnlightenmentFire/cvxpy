_CN = "零一二三四五六七八九"


def _int_cn(n):
    n = int(n)
    if n < 10:
        return _CN[n]
    if n < 20:
        return "十" + (_CN[n % 10] if n % 10 else "")
    if n < 100:
        return _CN[n // 10] + "十" + (_CN[n % 10] if n % 10 else "")
    if n < 1000:
        r = _CN[n // 100] + "百"
        rest = n % 100
        if rest == 0:
            return r
        return r + ("零" + _CN[rest] if rest < 10 else _int_cn(rest) if rest >= 20 else "一" + _int_cn(rest))
    if n < 10000:
        r = ("两" if n // 1000 == 2 else _CN[n // 1000]) + "千"
        rest = n % 1000
        if rest == 0:
            return r
        return r + ("零" + _int_cn(rest) if rest < 100 else _int_cn(rest))
    return str(n)


def spoken(text):
    t = text.replace("U-2", "U二")
    t = re.sub(r"(\d{4})年", lambda m: "".join(_CN[int(c)] for c in m.group(1)) + "年", t)
    t = re.sub(r"(\d+)多", lambda m: _int_cn(m.group(1)) + "多", t)
    t = re.sub(r"\d+", lambda m: _int_cn(m.group(0)), t)
    t = t.replace("“", "").replace("”", "").replace("——", "，")
    return t


def build():
    out = []
    for row in L:
        lid, shot, kind, text = row[:4]
        tts = row[4] if len(row) > 4 else spoken(text)
        out.append({"id": lid, "shot": shot, "kind": kind, "text": text, "tts": tts})
    os.makedirs(os.path.join(ROOT, "audio/full"), exist_ok=True)
    json.dump(out, open(os.path.join(ROOT, "audio/full/lines.json"), "w"), ensure_ascii=False, indent=1)
    n = sum(len(re.sub(r"[^一-鿿A-Za-z0-9]", "", o["text"])) for o in out)
    nq = sum(len(re.sub(r"[^一-鿿]", "", o["tts"])) for o in out if o["kind"] == "Q")
    nn = sum(len(re.sub(r"[^一-鿿]", "", o["tts"])) for o in out if o["kind"] == "N")
    est = nn / 5.1 + nq / 4.7 + 0.3 * len(out)
    print(f"{len(out)} lines, {n} chars; spoken narration {nn} + quotes {nq}; est. voice time {est:.0f}s")
    return out


