def all_lines():
    out = []
    for s in SCENES:
        for i, (txt, o) in enumerate(s["lines"]):
            out.append(dict(id=f"{s['id']}_{i:02d}", scene=s["id"], vis=s["vis"], text=txt,
                            say=o.get("say", txt).replace("《", "").replace("》", ""),
                            q=o.get("q"), gap=o.get("gap", 0.0)))
    return out


