def all_lines():
    out, k = [], 0
    for sc in SCENES:
        for it in sc["items"]:
            if it[0] == "n":
                k += 1
                out.append(dict(id=f"L{k:03d}", scene=sc["id"], say=it[1], sub=it[2] if len(it) > 2 else it[1]))
    return out


