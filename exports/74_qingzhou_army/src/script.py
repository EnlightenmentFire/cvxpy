TTS_FIX = {"宫请说州中": "宫请税州中", "济北": "己北", "燕、代": "烟、代", "东阿": "东婀", "窃为诸君": "窃位诸君"}


def tts_text(say):
    for a, b in TTS_FIX.items():
        say = say.replace(a, b)
    return say.replace("“", "").replace("”", "").replace("《", "").replace("》", "")


def all_lines():
    out = []
    for si, sc in enumerate(S):
        for li, d in enumerate(sc["lines"]):
            d = dict(d)
            d["id"] = f"{si + 1}{chr(97 + li // 26)}{li % 26:02d}"
            d["scene"] = sc["key"]
            out.append(d)
    return out


